_TOKEN_RE = re.compile(r"[A-Za-z]+")


def _cut_name(token: str) -> bool:
    """A name the bank's print width cut off ('SHAIK' of SHAIKH), or one that
    runs into the next word ('RAJESHKU' of RAJESH KUMAR)."""
    return len(token) >= 3 and any(n.startswith(token) or token.startswith(n) for n in _NAMES if len(n) >= 4)


def classify_payee(name: str | None) -> str:
    """'person', 'business', or 'unknown' for a UPI payee name."""
    if not name or not name.strip():
        return UNKNOWN
    if any(ch.isdigit() for ch in name):
        return BUSINESS
    raw_tokens = name.replace("/", " ").replace(".", " ").split()
    if not all(_TOKEN_RE.fullmatch(t) for t in raw_tokens):
        return UNKNOWN  # punctuation or symbols inside a word: not a plain name
    tokens = [t.upper() for t in raw_tokens]
    # 'M S KINGSTON' / 'M/S KINGSTON' is a firm (messrs), not Ms.
    if tokens[:2] == ["M", "S"] or any(t in _BUSINESS_MARKERS for t in tokens):
        return BUSINESS
    words = tokens[1:] if tokens[0] in _TITLES else tokens
    if not 1 <= len(words) <= 4 or (len(words) == 1 and words == tokens):
        return UNKNOWN  # one bare word could be a person or a brand ('ARJUN' vs 'Licious')
    cut_allowed = len(" ".join(name.split())) >= settings.counterparty_truncated_min_len

    def evidence(i: int, word: str) -> bool:
        return word in _NAMES or len(word) == 1 or (i == len(words) - 1 and cut_allowed and _cut_name(word))

    if all(evidence(i, w) for i, w in enumerate(words)) and any(w in _NAMES for w in words):
        return PERSON
    return UNKNOWN
